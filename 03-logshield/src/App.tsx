import { useState, useCallback } from 'react';
import type { ActivePage, DetectionConfig } from './types';
import { generateMockData } from './data/mockDataGenerator';
import { DEFAULT_DETECTION_CONFIG } from './features/logs/noiseReducer';
import { useAlerts } from './hooks/useAlerts';
import { Sidebar } from './components/Sidebar';
import { Header } from './components/Header';
import { DashboardPage } from './components/DashboardPage';
import { RawLogsPage } from './components/RawLogsPage';
import { AlertsPage } from './components/AlertsPage';
import { SettingsPage } from './components/SettingsPage';

export function App() {
  const [activePage, setActivePage] = useState<ActivePage>('dashboard');

  // Logs live in state so detection can be re-run when config changes.
  // Lazy initializer runs generateMockData() exactly once at mount.
  const [logs] = useState(generateMockData);

  // Detection thresholds — mutated by SettingsPage, trigger useMemo re-run in useAlerts
  const [detectionConfig, setDetectionConfig] = useState<DetectionConfig>(DEFAULT_DETECTION_CONFIG);

  const { alerts } = useAlerts(logs, detectionConfig);

  const navigate = (page: ActivePage) => setActivePage(page);

  const handleConfigChange = useCallback((patch: Partial<DetectionConfig>) => {
    setDetectionConfig((prev) => ({ ...prev, ...patch }));
  }, []);

  return (
    <div className="flex min-h-screen bg-bg text-text-primary">
      <Sidebar
        activePage={activePage}
        onNavigate={navigate}
        alertCount={alerts.length}
      />

      {/* Main content — offset by sidebar width */}
      <div className="flex-1 flex flex-col ml-56">
        <Header
          activePage={activePage}
          alertCount={alerts.length}
          onNavigate={navigate}
        />

        {/* Page content — offset below header */}
        <main className="flex-1 mt-14 p-6 min-w-0">
          <div className="mb-5">
            <h1 className="text-xl font-bold text-text-primary">
              {activePage === 'dashboard' && 'Security Operations Dashboard'}
              {activePage === 'logs' && 'Raw Log Stream'}
              {activePage === 'alerts' && 'Alert Center'}
              {activePage === 'settings' && 'Configuration'}
            </h1>
            <p className="text-xs text-text-muted mt-0.5">
              {activePage === 'dashboard' && 'Synthetic log analysis — rule-based brute force and location-label change heuristics'}
              {activePage === 'logs' && 'Synthetic event feed with search, sort, and filter'}
              {activePage === 'alerts' && 'Correlated alerts generated by the noise-reduction engine'}
              {activePage === 'settings' && 'Adjust detection thresholds and watch alerts update live'}
            </p>
          </div>

          {activePage === 'dashboard' && (
            <DashboardPage logs={logs} alerts={alerts} />
          )}
          {activePage === 'logs' && (
            <RawLogsPage logs={logs} />
          )}
          {activePage === 'alerts' && (
            <AlertsPage alerts={alerts} />
          )}
          {activePage === 'settings' && (
            <SettingsPage config={detectionConfig} onConfigChange={handleConfigChange} />
          )}
        </main>
      </div>
    </div>
  );
}

export default App;
